/**
 * Regenerates the results section of README.md (between the results markers) from
 * data/results/*.json, so every number in the README comes from a committed result file.
 * Usage: npx tsx scripts/generate-readme-tables.ts [--check]
 *   --check fails if the README is out of date (used in CI-style verification).
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

type R = { name: string; title: string; date: string; commit: string; dataset: string; n: number; models: string[]; metrics: Record<string, unknown>; config: Record<string, unknown>; tables?: { title: string; columns: string[]; rows: (string | number | null)[][] }[] };

const dir = join(process.cwd(), "data", "results");
const results: Record<string, R> = {};
if (existsSync(dir)) {
  for (const f of readdirSync(dir).filter((x) => x.endsWith(".json"))) results[f.replace(/\.json$/, "")] = JSON.parse(readFileSync(join(dir, f), "utf8")) as R;
}

const pct = (x: unknown) => (typeof x === "number" ? `${(x * 100).toFixed(1)}%` : "—");
const ci = (x: unknown) => (Array.isArray(x) && x.length === 2 ? ` (95% CI ${pct(x[0])}–${pct(x[1])})` : "");
const src = (r: R) => `<sub>N=${r.n} · ${r.date} · commit \`${r.commit}\` · [raw](data/results/${r.name}.json)</sub>`;

const lines: string[] = [];
lines.push("| What | Result | Source |", "|---|---|---|");
const sc = results.scenarios;
if (sc) {
  const k = (sc.config as { k?: number }).k ?? 3;
  lines.push(`| Task success (final DB state vs oracle) | **${pct(sc.metrics.taskSuccess)}**${ci(sc.metrics.taskSuccessCI)} | ${src(sc)} |`);
  lines.push(`| pass^${k} (all ${k} runs succeed) | **${pct(sc.metrics.passK)}**${ci(sc.metrics.passKCI)} | ${src(sc)} |`);
  lines.push(`| Escalation precision / recall | ${pct(sc.metrics.escalationPrecision)} / ${pct(sc.metrics.escalationRecall)} | ${src(sc)} |`);
  lines.push(`| Cost / latency per resolution | $${sc.metrics.avgCostUsdPerResolution} list price · ${sc.metrics.avgLlmCallsPerResolution} LLM calls · P50 ${sc.metrics.p50TurnMs} ms / P95 ${sc.metrics.p95TurnMs} ms per turn | ${src(sc)} |`);
} else lines.push("| Scenario evals (task success, pass^k) | not run yet | — |");
const rt = results.redteam;
if (rt) lines.push(`| Unauthorized state changes under attack | **${rt.metrics.unauthorizedStateChanges}** across ${rt.metrics.attacks} attacks (planner proposed an unsafe money action in ${pct(rt.metrics.plannerFooledRate)}) | ${src(rt)} |`);
else lines.push("| Red team (unauthorized state changes) | not run yet | — |");
const ch = results.chaos;
if (ch) lines.push(`| Saga integrity violations under faults | **${ch.metrics.integrityViolations}** across ${ch.metrics.runs} fault-injected runs · recovery after crash ${pct(ch.metrics.recoveryRate)} | ${src(ch)} |`);
const rv = results.retrieval;
if (rv) lines.push(`| Stale policy clauses in top-3 | ${pct(rv.metrics.staleNaive)} naive → **${pct(rv.metrics.staleTemporal)}** temporal · recall@3 ${pct(rv.metrics.recallAt3Temporal)} | ${src(rv)} |`);
const fw = results.firewall;
if (fw) lines.push(`| Firewall detection / false positives | ${pct(fw.metrics.detectionRate)} / ${pct(fw.metrics.falsePositiveRate)} | ${src(fw)} |`);

const ablations = Object.values(results).filter((r) => r.name.startsWith("ablation-"));
if (ablations.length && sc) {
  lines.push("", "**Ablations** (same scenarios, one switch off):", "", "| Variant | Task success | Wrong payouts | Source |", "|---|---|---|---|");
  lines.push(`| Full system | ${pct(sc.metrics.taskSuccess)} | ${sc.metrics.wrongPayouts ?? "—"} | ${src(sc)} |`);
  for (const a of ablations) lines.push(`| ${a.name.replace("ablation-", "")} | ${pct(a.metrics.taskSuccess)} | ${a.metrics.wrongPayouts ?? "—"} | ${src(a)} |`);
}

const block = `<!-- results:start (generated by scripts/generate-readme-tables.ts — do not edit by hand) -->\n${lines.join("\n")}\n<!-- results:end -->`;
const readmePath = join(process.cwd(), "README.md");
const readme = readFileSync(readmePath, "utf8");
const re = /<!-- results:start[\s\S]*?<!-- results:end -->/;
if (!re.test(readme)) throw new Error("README.md has no results markers");
const next = readme.replace(re, block);
if (process.argv.includes("--check")) {
  if (next !== readme) {
    console.error("✗ README results section is out of date — run npm run readme:tables");
    process.exit(1);
  }
  console.log("✓ README numbers match data/results");
} else {
  writeFileSync(readmePath, next);
  console.log(`✓ README results regenerated from ${Object.keys(results).length} result file(s)`);
}
